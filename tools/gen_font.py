#!/usr/bin/env python3
"""Generate src/user/src/font.rs from a Linux console PSF2 font (Terminus 16x32).

Terminus is copyright (c) Dimitar Zhekov, SIL Open Font License 1.1
(https://terminus-font.sourceforge.net/). Only the printable ASCII range is embedded.

    tools/gen_font.py [FONT.psf.gz] > src/user/src/font.rs
"""

import gzip
import struct
import sys

DEFAULT = "/usr/share/consolefonts/CyrAsia-Terminus32x16.psf.gz"
FIRST, LAST = 0x20, 0x7E


def load(path: str) -> bytes:
    opener = gzip.open if path.endswith(".gz") else open
    with opener(path, "rb") as f:
        return f.read()


def glyph_index_by_codepoint(
    data: bytes, header_size: int, length: int, charsize: int
) -> dict[int, int]:
    """Map Unicode code points to glyph indexes using the PSF2 unicode table."""
    table = data[header_size + length * charsize :]
    mapping: dict[int, int] = {}
    glyph = 0
    pos = 0
    while pos < len(table) and glyph < length:
        end = table.index(b"\xff", pos)
        entry = table[pos:end]
        single = entry.split(b"\xfe")[0]
        for ch in single.decode("utf-8"):
            mapping.setdefault(ord(ch), glyph)
        pos = end + 1
        glyph += 1
    return mapping


def main() -> None:
    data = load(sys.argv[1] if len(sys.argv) > 1 else DEFAULT)
    magic, _version, header_size, flags, length, charsize, height, width = struct.unpack(
        "<8I", data[:32]
    )
    if magic != 0x864AB572 or width != 16 or height != 32:
        sys.exit("expected a PSF2 font with 16x32 glyphs")
    if not flags & 1:
        sys.exit("font has no unicode table")
    index = glyph_index_by_codepoint(data, header_size, length, charsize)
    row_bytes = (width + 7) // 8

    print("// @generated by tools/gen_font.py from Terminus 16x32 (SIL OFL 1.1, Dimitar Zhekov).")
    print("// Do not edit by hand.")
    print()
    print("pub const GLYPH_W: usize = 16;")
    print("pub const GLYPH_H: usize = 32;")
    print(f"pub const FIRST: u8 = {FIRST:#04x};")
    print(f"pub const LAST: u8 = {LAST:#04x};")
    print()
    print("/// One `u16` per row; bit 15 is the leftmost pixel.")
    print("#[rustfmt::skip]")
    print(f"pub static GLYPHS: [[u16; GLYPH_H]; {LAST - FIRST + 1}] = [")
    for code in range(FIRST, LAST + 1):
        base = header_size + index[code] * charsize
        rows = [
            int.from_bytes(data[base + r * row_bytes : base + (r + 1) * row_bytes], "big")
            for r in range(height)
        ]
        body = ", ".join(f"{row:#06x}" for row in rows)
        print(f"    [{body}], // {chr(code)!r}")
    print("];")


if __name__ == "__main__":
    main()
